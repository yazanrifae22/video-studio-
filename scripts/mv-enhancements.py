"""Roll up Mission Voices per-video enhancement logs into docs/brands/clipping/enhancements-log.md.

Reads productions/clip-*/enhancements.json (written by the showrunner) and recomputes shot stats from cutlist.json,
so the table shows what was actually built. `results` (YouTube Studio numbers) is filled in later per clip.
Usage: python scripts/mv-enhancements.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs' / 'brands' / 'clipping' / 'enhancements-log.md'
RULES = ['R1', 'R2', 'R3', 'R4', 'R5', 'R6', 'R7', 'R8']


def load(p: Path):
    try:
        return json.loads(p.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None


def shot_stats(cl):
    """Shot = one cut-list segment (contiguous splits count: they change framing)."""
    d = [s['src_out'] - s['src_in'] for s in (cl or {}).get('segments', [])]
    if not d:
        return None
    return {'shots': len(d), 'duration_s': round(sum(d), 1), 'max_shot_s': round(max(d), 1), 'avg_shot_s': round(sum(d) / len(d), 1)}


def main():
    rows = []
    for prod in sorted((ROOT / 'productions').glob('clip-*')):
        log = load(prod / 'enhancements.json')
        if log is None:
            continue
        st = shot_stats(load(prod / 'cutlist.json')) or {}
        applied = {r['id'] for r in log.get('rules', []) if r.get('applied')}
        res = log.get('results') or {}
        rows.append([
            prod.name, log.get('ruleset', '?'), str(st.get('duration_s', '')), str(st.get('shots', '')), str(st.get('max_shot_s', '')),
            str(log.get('dead_air_removed_s', '')), ' '.join(r if r in applied else '·' for r in RULES),
            f"{(log.get('cta') or {}).get('id', '')} {(log.get('cta') or {}).get('text', '')}".strip(),
            (log.get('hook') or {}).get('text', ''), str((log.get('retention_review') or {}).get('score', '')),
            str(res.get('avg_pct_viewed', '')), str(res.get('stayed_pct', '')), str(res.get('subs', '')), str(res.get('comments', '')),
        ])
    head = ['Production', 'Ruleset', 'Dur s', 'Shots', 'Max shot s', 'Dead air cut s', 'Rules applied', 'CTA', 'Hook', 'Retention review',
            'Avg % viewed', 'Stayed %', 'Subs', 'Comments']
    lines = ['# Mission Voices — enhancement log', '',
             'Generated by `python scripts/mv-enhancements.py` from each `productions/<id>/enhancements.json` (rules: goal-28.md "Retention rules v1").',
             'Shot stats are recomputed from the cut list. Results columns are filled from YouTube Studio after publishing.', '',
             '| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    lines += ['| ' + ' | '.join(c.replace('|', '/') for c in r) + ' |' for r in rows]
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(rows)} clips -> {OUT}')


if __name__ == '__main__':
    main()
